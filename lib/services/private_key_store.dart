import 'dart:io';
import 'package:path_provider/path_provider.dart';

/// Keeps imported SSH private keys in the app's private storage.
///
/// On Android that folder is sandboxed to this app, so other apps cannot read
/// it; on desktop it sits in the user's profile, like `~/.ssh`. The key is not
/// encrypted on top of that. (A platform keystore would be better, but
/// `flutter_secure_storage` needs the ATL component of Visual Studio on
/// Windows, which would break plain `flutter build windows`.)
class PrivateKeyStore {
  static Future<File> _file(String profileId) async {
    final base = await getApplicationSupportDirectory();
    final dir = Directory('${base.path}${Platform.pathSeparator}keys');
    if (!await dir.exists()) await dir.create(recursive: true);
    // The id is generated by the app, but never trust it as a path.
    final safe = profileId.replaceAll(RegExp(r'[^A-Za-z0-9_-]'), '_');
    return File('${dir.path}${Platform.pathSeparator}$safe.key');
  }

  static Future<void> save(String profileId, String key) async {
    final file = await _file(profileId);
    await file.writeAsString(key, flush: true);
    if (Platform.isLinux || Platform.isMacOS) {
      try {
        await Process.run('chmod', ['600', file.path]);
      } catch (_) {}
    }
  }

  static Future<String?> load(String profileId) async {
    final file = await _file(profileId);
    return await file.exists() ? file.readAsString() : null;
  }

  static Future<void> delete(String profileId) async {
    final file = await _file(profileId);
    if (await file.exists()) await file.delete();
  }
}
