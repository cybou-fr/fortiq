#pragma once

#include <QByteArray>
#include <QString>
#include <QStringList>
#include <QVariantList>
#include <QVariantMap>

namespace fortiq {

// Network app (read-only): a snapshot of interfaces, routes, listening ports and
// DNS from the selected Linux server, plus small diagnostics (resolve, ping,
// trace). Everything is existing tools run over SSH (`ip -j`, `ss`, `getent`,
// `ping`, `tracepath`); nothing is changed on the server. See docs/NETWORK.md.

struct NetAddress {
    QString family;    // "inet" | "inet6"
    QString address;
    int prefix = 0;
    QString scope;     // host | link | global
};

struct NetInterface {
    QString name;
    int index = 0;
    QString state;     // UP | DOWN | UNKNOWN ...
    int mtu = 0;
    QString mac;
    QString kind;      // loopback | ether | none ...
    QStringList flags;
    QList<NetAddress> addresses;
    bool hasStats = false;
    qint64 rxBytes = 0, txBytes = 0, rxPackets = 0, txPackets = 0, rxErrors = 0, txErrors = 0, rxDropped = 0, txDropped = 0;
};

struct NetRoute {
    QString family;    // inet | inet6
    QString destination;
    QString gateway;
    QString device;
    QString protocol;
    QString prefsrc;
    int metric = -1;
    bool isDefault = false;
};

struct NetListener {
    QString protocol;  // tcp | udp
    QString state;
    QString address;   // as printed by ss, without the port
    int port = 0;
    QString process;   // empty when ss could not tell (not your process / not root)
    int pid = 0;
    QString exposure;  // "all" (0.0.0.0, ::), "local" (127.x, ::1), "address" (one interface)
    qint64 recvQ = 0, sendQ = 0;
};

struct NetSnapshot {
    bool ok = false;
    QString problem;               // why nothing usable came back
    QString hostname;
    QList<NetInterface> interfaces;
    QList<NetRoute> routes;
    QList<NetListener> listeners;
    bool processInfoMissing = false;   // some listeners have no process name
    QStringList dnsServers;
    QStringList dnsSearch;
    QString dnsNote;               // e.g. generated by WSL / systemd-resolved
    QString resolvedText;          // `resolvectl status` text, when available
    QStringList tools;             // available: ping, dig, getent, tracepath, mtr
    QStringList notes;
};

// Script for `sh -s`: prints "#section <name>" frames. Read-only.
QByteArray buildNetSnapshotScript();

// Parses the frames. Tolerant: a missing tool produces a note, not a failure.
NetSnapshot parseNetSnapshot(const QByteArray &output);

// Individual parsers (exposed for tests).
QList<NetInterface> parseIpAddrJson(const QByteArray &json);
void mergeLinkStats(QList<NetInterface> &interfaces, const QByteArray &json);
QList<NetRoute> parseIpRouteJson(const QByteArray &json, const QString &family);
QList<NetListener> parseSs(const QByteArray &text);
void parseResolvConf(const QByteArray &text, QStringList &servers, QStringList &search, QString &note);

// QML views.
QVariantList interfacesToVariant(const QList<NetInterface> &list);
QVariantList routesToVariant(const QList<NetRoute> &list);
QVariantList listenersToVariant(const QList<NetListener> &list);

// Diagnostics: kind = "resolve" | "ping" | "trace". The target must be a host name or an
// IP literal (no spaces, no leading dash, no shell characters); otherwise `error` is set
// and the script is empty. The target is data inside the script, never an argument of sh.
QByteArray buildProbeScript(const QString &kind, const QString &target, QString *error);
bool isValidProbeTarget(const QString &target);

QString humanBytes(qint64 bytes);

}  // namespace fortiq
